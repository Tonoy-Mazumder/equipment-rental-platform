import type { Metadata } from "next";
import { DM_Sans, Geist_Mono, Manrope } from "next/font/google";
import { SiteChrome } from "@/components/site-chrome";
import "./globals.css";

// Manrope is used for all headings: h1–h4, hero titles, section headings,
// card titles, and dashboard page titles.
const manrope = Manrope({
  variable: "--font-manrope",
  subsets: ["latin"],
});

// DM Sans is used for all body content: paragraphs, navigation links,
// buttons, form labels and inputs, descriptions, tables, badges, and metadata.
const dmSans = DM_Sans({
  variable: "--font-dm-sans",
  subsets: ["latin"],
});

// Geist Mono is reserved for code snippets and terminal output.
const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "RentPro",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${manrope.variable} ${dmSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <SiteChrome>{children}</SiteChrome>
      </body>
    </html>
  );
}
